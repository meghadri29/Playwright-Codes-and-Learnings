// For Loop
// Help you to repeat a block of code.

// ICU
// INIT - let i=0
// CONDITION -  i< 10

for (let i = 0; i < 10; i++) {
    console.log(i);
}

for (let i = 0; i < 10; ++i) {
    console.log(i);
}

let a = 10;
let b = ++a;
console.log(a);
console.log(b);

// //  Exp and Result Table
// // Line No | a | Result b
// // 1       |  10 |  NA
// // 2       |  11 |  11
// // 3       | 11 - print | 11
// // 4       | 11 | 11 - print