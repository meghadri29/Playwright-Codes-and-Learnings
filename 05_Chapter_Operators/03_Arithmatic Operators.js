// Assignment Operators
let a = 10;
let b = 5;

// Arithmetic Operators
let sum = a + b; // Addition
let sub = a - b; // Subtraction
let mul = a * b; // Multiplication
let div = a / b; // Division

console.log(sum); // Output: 15
console.log(sub); // Output: 5
console.log(mul); // Output: 50
console.log(div); //output: 2

// Modulus -> % -> It will give you remainder
console.log(a%b);
console.log(13%7);
console.log(18%2);
console.log(108%50);

// n%2=1 - Odd Number
// n%2=0 - Even Number

// Exponential **, power 2^3->8
console.log(2**3);
console.log(a**b); // 10 ^ 3 ->1000


