let age='Meghadri'; //string literal.
let isStudent=true; //This is boolean literal assigned to the variable isStudent.
let pi=3.14; //This is a number literal assigned to the variable pi.
let name='Meghadri'; //This is a string literal assigned to the variable name.
let nullValue=null; //This is a null literal assigned to the variable nullValue.
